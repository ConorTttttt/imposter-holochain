#!/usr/bin/env python3
"""Deterministic RFC 9180 / native-Holochain 0.7 PUBLIC signed test vectors.

Input: JSON hash strings generated by native-role-vectors.rs on pinned Holochain 0.7.
Output: public enc/ciphertext, headers, AAD, signatures. Seeds are synthetic, fixed
TEST-ONLY keys in source. No deployable keys or real role plaintext in output.
"""
import base64
import hashlib
import hmac
import json
import struct
import sys

from cryptography.hazmat.primitives.asymmetric import ed25519, x25519
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

DOMAIN = "imposter.h2hc.private-role.v1"
SIGN_PREFIX = b"IMPOSTER-H2HC-ROLE-SIGNED\x00\x01"
AAD_PREFIX = b"IMPOSTER-H2HC-ROLE-AAD\x00\x01"
INFO = b"imposter.h2hc.private-role/hpke-v1"
KEM_SUITE = b"KEM" + (32).to_bytes(2, "big")
HPKE_SUITE = b"HPKE" + (32).to_bytes(2, "big") + (1).to_bytes(2, "big") + (2).to_bytes(2, "big")


def raw_hash(s):
    assert s[0] == "u"
    out = base64.urlsafe_b64decode(s[1:] + "=" * (-len(s[1:]) % 4))
    assert len(out) == 39
    return out


def hdr(e, op):
    reply = b"\x00" if e["in_reply_to"] is None else b"\x01" + bytes.fromhex(e["in_reply_to"])
    return b"".join([
        bytes([1 if op == "role_request_v1" else 2]),
        raw_hash(e["dna_hash"]), raw_hash(e["sender_agent"]),
        raw_hash(e["recipient_agent"]), raw_hash(e["role_commit"]),
        struct.pack(">H", e["seat"]), bytes.fromhex(e["recipient_key_id"]),
        struct.pack(">Q", e["recipient_key_epoch"]), bytes.fromhex(e["message_id"]), struct.pack(">Q", e["created_at_ms"]),
        struct.pack(">Q", e["expires_at_ms"]), reply,
    ])


def extract(salt, data):
    return hmac.new(salt or bytes(32), data, hashlib.sha256).digest()


def expand(prk, info, length):
    out = b""
    t = b""
    i = 0
    while len(out) < length:
        i += 1
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t
    return out[:length]


def labeled_extract(suite, salt, label, data):
    return extract(salt, b"HPKE-v1" + suite + label + data)


def labeled_expand(suite, prk, label, info, length):
    return expand(prk, struct.pack(">H", length) + b"HPKE-v1" + suite + label + info, length)


def schedule(dh, enc, pk_r):
    eae_prk = labeled_extract(KEM_SUITE, b"", b"eae_prk", dh)
    shared_secret = labeled_expand(KEM_SUITE, eae_prk, b"shared_secret", enc + pk_r, 32)
    psk_id_hash = labeled_extract(HPKE_SUITE, b"", b"psk_id_hash", b"")
    info_hash = labeled_extract(HPKE_SUITE, b"", b"info_hash", INFO)
    ctx = b"\x00" + psk_id_hash + info_hash
    secret = labeled_extract(HPKE_SUITE, shared_secret, b"secret", b"")
    key = labeled_expand(HPKE_SUITE, secret, b"key", ctx, 32)
    nonce = labeled_expand(HPKE_SUITE, secret, b"base_nonce", ctx, 12)
    return key, nonce


def hpke_encrypt(seed_recipient, seed_ephemeral, plaintext, aad):
    sk_r = x25519.X25519PrivateKey.from_private_bytes(bytes([seed_recipient]) * 32)
    pk_r = sk_r.public_key()
    pk_r_raw = pk_r.public_bytes(Encoding.Raw, PublicFormat.Raw)
    sk_e = x25519.X25519PrivateKey.from_private_bytes(bytes([seed_ephemeral]) * 32)
    enc = sk_e.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    key, nonce = schedule(sk_e.exchange(pk_r), enc, pk_r_raw)
    ciphertext = AESGCM(key).encrypt(nonce, plaintext, aad)
    # Independent receiver key schedule and base-mode authentication.
    key_r, nonce_r = schedule(sk_r.exchange(sk_e.public_key()), enc, pk_r_raw)
    assert AESGCM(key_r).decrypt(nonce_r, ciphertext, aad) == plaintext
    bad = False
    try:
        AESGCM(key_r).decrypt(nonce_r, ciphertext, aad + b"!")
    except Exception:
        bad = True
    assert bad, "tampered HPKE associated data must fail"
    wrong = x25519.X25519PrivateKey.from_private_bytes(bytes([99]) * 32)
    wrong_pk = wrong.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    key_w, nonce_w = schedule(wrong.exchange(sk_e.public_key()), enc, wrong_pk)
    try:
        AESGCM(key_w).decrypt(nonce_w, ciphertext, aad)
        raise AssertionError("foreign recipient decrypted role ciphertext")
    except Exception as err:
        if isinstance(err, AssertionError):
            raise
    return enc, ciphertext, pk_r_raw


def main():
    hashes = json.load(open(sys.argv[1], encoding="utf-8"))
    cases = []
    key_attestations = []
    for op, agent_seed, recipient_seed, ephemeral_seed, ident, reply, epoch, keyhex in [
        ("role_request_v1", 28, 51, 61, "22" * 16, None, 7, "11" * 16),
        ("role_delivery_v1", 27, 52, 62, "33" * 16, "22" * 16, 9, "44" * 16),
    ]:
        sender = "agent_b" if op == "role_request_v1" else "agent_a"
        recipient = "agent_a" if op == "role_request_v1" else "agent_b"
        e = {
            "version": 1, "domain": DOMAIN, "dna_hash": hashes["dna"],
            "sender_agent": hashes[sender], "recipient_agent": hashes[recipient],
            "role_commit": hashes["commit"], "seat": 1,
            "recipient_key_id": keyhex, "recipient_key_epoch": epoch, "message_id": ident,
            "created_at_ms": 1700000000000, "expires_at_ms": 1700000030000,
            "in_reply_to": reply, "hpke_enc": "", "ciphertext": "",
        }
        aad = AAD_PREFIX + hdr(e, op)
        clear = b"synthetic-not-a-game-role"
        enc, ct, pk = hpke_encrypt(recipient_seed, ephemeral_seed, clear, aad)
        e["hpke_enc"] = base64.b64encode(enc).decode()
        e["ciphertext"] = base64.b64encode(ct).decode()
        preimage = SIGN_PREFIX + hdr(e, op) + enc + struct.pack(">I", len(ct)) + ct
        sk = ed25519.Ed25519PrivateKey.from_private_bytes(bytes([agent_seed]) * 32)
        sig = sk.sign(preimage)
        sk.public_key().verify(sig, preimage)
        # Per-cell Lair-signed encryption-key attestation. Public fixture only.
        key_id = bytes.fromhex(e["recipient_key_id"])
        attest_before = 1699999000000
        attest_after = 1700000099999
        attest_bytes = b"".join([
            b"IMPOSTER-H2HC-ROLE-KEY\x00\x01",
            raw_hash(e["dna_hash"]), raw_hash(e["recipient_agent"]),
            key_id, pk, struct.pack(">Q", epoch),
            struct.pack(">Q", attest_before), struct.pack(">Q", attest_after),
        ])
        recipient_signer = 27 if recipient == "agent_a" else 28
        signer = ed25519.Ed25519PrivateKey.from_private_bytes(bytes([recipient_signer]) * 32)
        attest_sig = signer.sign(attest_bytes)
        signer.public_key().verify(attest_sig, attest_bytes)
        key_attestations.append({
            "dna_hash": e["dna_hash"], "agent": e["recipient_agent"],
            "key_id": e["recipient_key_id"], "epoch": epoch,
            "not_before_ms": attest_before, "not_after_ms": attest_after,
            "x25519_public_key_b64": base64.b64encode(pk).decode(),
            "signed_bytes_hex": attest_bytes.hex(),
            "signature_b64": base64.b64encode(attest_sig).decode(),
            "signature_hex": attest_sig.hex(),
        })
        cases.append({
            "operation": op, "envelope": e,
            "signature_b64": base64.b64encode(sig).decode(),
            "signed_bytes_hex": preimage.hex(), "aad_hex": aad.hex(),
            "header_hex": hdr(e, op).hex(), "hpke_info_hex": INFO.hex(),
            "hpke_enc_hex": enc.hex(), "ciphertext_hex": ct.hex(),
            "signature_hex": sig.hex(),
            "recipient_hpke_pk_b64": base64.b64encode(pk).decode(),
            "plaintext_sha256": hashlib.sha256(clear).hexdigest(),
            "suite": "HPKE-v1/DHKEM(X25519,HKDF-SHA256)/HKDF-SHA256/AESGCM",
        })
    # Declarative negative mutations are directly usable by HWC's fixture importer.
    # They retain the ORIGINAL signatures, so every modified signed field must fail.
    negatives = [
        {"name": "wrong_sender_signature", "case": 1, "mutate": {"signature_b64": base64.b64encode(bytes(64)).decode()}, "reject_at": "gateway"},
        {"name": "wrong_recipient", "case": 1, "mutate": {"envelope.recipient_agent": hashes["agent_c"]}, "reject_at": "gateway_or_receiver"},
        {"name": "wrong_dna", "case": 1, "mutate": {"envelope.dna_hash": hashes["other_dna"]}, "reject_at": "gateway_or_receiver"},
        {"name": "expired_envelope", "case": 1, "mutate": {"envelope.expires_at_ms": 1699999999999}, "reject_at": "gateway_or_receiver"},
        {"name": "old_key_epoch", "case": 1, "mutate": {"envelope.recipient_key_epoch": 8}, "reject_at": "receiver_or_bad_signature"},
        {"name": "key_epoch_zero", "case": 1, "mutate": {"envelope.recipient_key_epoch": 0}, "reject_at": "gateway"},
        {"name": "tampered_ciphertext", "case": 1, "mutate": {"envelope.ciphertext": base64.b64encode(bytes(32)).decode()}, "reject_at": "gateway_or_receiver"},
        {"name": "request_with_reply_id", "case": 0, "mutate": {"envelope.in_reply_to": "77" * 16}, "reject_at": "gateway"},
        {"name": "mismatched_request_id", "case": 1, "mutate": {"envelope.in_reply_to": "88" * 16}, "reject_at": "receiver"},
    ]
    assert cases[0]["envelope"]["message_id"] == cases[1]["envelope"]["in_reply_to"]
    assert cases[0]["envelope"]["recipient_key_epoch"] != cases[1]["envelope"]["recipient_key_epoch"]
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        json.dump({"version": 1, "status": "candidate-pending-agent2-approval",
                   "cases": cases, "key_attestations": key_attestations,
                   "negative_cases": negatives, "fixture_only": True}, f, indent=2)
    print("DETERMINISTIC_HPKE_VECTORS=PASS; recipient and wrong-AAD/foreign-recipient checks pass")


